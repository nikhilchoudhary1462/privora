import ExifReader from 'exifreader';

// Construct a valid JPEG binary with APP1 EXIF segment containing GPS tags
function buildGeotaggedJpegBase64() {
  // A tiny 1x1 or valid JPEG with real APP1 EXIF segment (TIFF header, GPS IFD, Make, Model, DateTime)
  // Let's create an APP1 EXIF buffer
  // Standard JPEG SOI: FF D8
  // APP1 Marker: FF E1, length: ...
  // "Exif\0\0"
  // TIFF Header: "II\x2A\x00\x08\x00\x00\x00" (Little Endian)
  
  // Or let's test a known binary structure
  const header = Buffer.from([
    0xff, 0xd8, // SOI
    0xff, 0xe1, 0x00, 0x90, // APP1 marker + length (144 bytes)
    0x45, 0x78, 0x69, 0x66, 0x00, 0x00, // "Exif\0\0"
    0x49, 0x49, 0x2a, 0x00, 0x08, 0x00, 0x00, 0x00, // TIFF Header (Little Endian)
    
    // IFD0: 2 entries
    0x02, 0x00,
    // Tag 1: Make (0x010F), ASCII (2), count 6, offset
    0x0f, 0x01, 0x02, 0x00, 0x06, 0x00, 0x00, 0x00, 0x26, 0x00, 0x00, 0x00,
    // Tag 2: GPSInfo IFD Pointer (0x8825), LONG (4), count 1, offset 0x30
    0x25, 0x88, 0x04, 0x00, 0x01, 0x00, 0x00, 0x00, 0x30, 0x00, 0x00, 0x00,
    // Next IFD offset: 0
    0x00, 0x00, 0x00, 0x00,
    
    // String "Apple\0" at offset 0x26 (38)
    0x41, 0x70, 0x70, 0x6c, 0x65, 0x00, 0x00, 0x00,
    
    // GPS IFD at offset 0x30 (48): 3 entries
    0x03, 0x00,
    // GPS Tag 1: GPSLatitudeRef (0x0001), ASCII (2), count 2, value "N\0"
    0x01, 0x00, 0x02, 0x00, 0x02, 0x00, 0x00, 0x00, 0x4e, 0x00, 0x00, 0x00,
    // GPS Tag 2: GPSLatitude (0x0002), RATIONAL (5), count 3, offset 0x5e (94)
    0x02, 0x00, 0x05, 0x00, 0x03, 0x00, 0x00, 0x00, 0x5e, 0x00, 0x00, 0x00,
    // GPS Tag 3: GPSLongitudeRef (0x0003), ASCII (2), count 2, value "E\0"
    0x03, 0x00, 0x02, 0x00, 0x02, 0x00, 0x00, 0x00, 0x45, 0x00, 0x00, 0x00,
    // Next IFD: 0
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    
    // GPS Latitude values: 28/1, 36/1, 50/1 (28.6139° N)
    0x1c, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, // 28/1
    0x24, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, // 36/1
    0x32, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, // 50/1
    
    // Minimal JPEG Image payload: SOF0, SOS, EOI
    0xff, 0xc0, 0x00, 0x0b, 0x08, 0x00, 0x10, 0x00, 0x10, 0x01, 0x01, 0x11, 0x00,
    0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0xd2,
    0xff, 0xd9 // EOI
  ]);

  return header;
}

const buf = buildGeotaggedJpegBase64();
const tags = ExifReader.load(buf, { expanded: true });
console.log('Successfully parsed GPS tags:', JSON.stringify(tags.gps, null, 2));
console.log('Successfully parsed Make tags:', JSON.stringify(tags.exif, null, 2));
